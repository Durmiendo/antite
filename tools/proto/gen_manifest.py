"""Writes proto-loader's manifest from the GeckoView AAR manifest.

The shell does not depend on GeckoView at build time (compileOnly), so the
manifest merger never sees GeckoView's services; they are copied here.

Usage: python3 -I tools/proto/gen_manifest.py path/to/geckoview.aar
"""
import re
import sys
import zipfile

APP_ID = "dev.antite.proto"
OUT = "proto-loader/src/main/AndroidManifest.xml"

src = zipfile.ZipFile(sys.argv[1]).read("AndroidManifest.xml").decode()
src = src.replace("${applicationId}", APP_ID)
perms = re.findall(r"<uses-permission[^>]*/>", src)
features = re.findall(r"<uses-feature[^>]*/>", src, re.S)
app_open = re.search(r"<application([^>]*)>", src)
zygote = re.search(r'android:zygotePreloadName="([^"]+)"', app_open.group(1)).group(1)
body = src[app_open.end():src.index("</application>")]

out = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/proto/gen_manifest.py from the GeckoView AAR. Do not edit. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">

    {chr(10).join("    " + p for p in perms).strip()}
    {chr(10).join("    " + f for f in features).strip()}

    <application
        android:name=".ProtoApp"
        android:appComponentFactory="dev.antite.proto.ProtoFactory"
        android:zygotePreloadName="{zygote}"
        android:label="Antite proto"
        android:extractNativeLibs="false"
        tools:replace="android:appComponentFactory"
        tools:targetApi="q">
        <activity android:name=".MainActivity" android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <data android:scheme="http" />
                <data android:scheme="https" />
            </intent-filter>
        </activity>
{body}
    </application>
</manifest>
"""
open(OUT, "w").write(out)
print("wrote", OUT)
